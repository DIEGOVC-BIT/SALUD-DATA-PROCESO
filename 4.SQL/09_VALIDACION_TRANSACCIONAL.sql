/* DATASALUD PERU - VERIFICACION DE CONSISTENCIA TRANSACCIONAL.
   Prueba no destructiva: el ROLLBACK FINAL deshace la modificacion de prueba.
   La auditoria que se genera dentro de la transaccion tambien se revierte;
   esto es la propiedad de atomicidad, NO una falla del trigger.
*/
USE MINSA;
GO
DECLARE @Id BIGINT=(SELECT MIN(ID_ATENCION) FROM dbo.ATENCIONES_SIS_OFICIAL);
IF @Id IS NULL THROW 54010,N'Primero ejecute la carga oficial SIS.',1;
DECLARE @ValorOriginal BIGINT=(SELECT ATENCIONES FROM dbo.ATENCIONES_SIS_OFICIAL WHERE ID_ATENCION=@Id);
BEGIN TRY
 BEGIN TRANSACTION;
 SAVE TRANSACTION PUNTO_PRUEBA;
 UPDATE dbo.ATENCIONES_SIS_OFICIAL SET ATENCIONES=ATENCIONES+1 WHERE ID_ATENCION=@Id;
 SELECT N'DENTRO DE TRANSACCION' AS Momento,ID_ATENCION,ATENCIONES
 FROM dbo.ATENCIONES_SIS_OFICIAL WHERE ID_ATENCION=@Id;
 SELECT TOP(5) ACCION,ID_ATENCION,ATENCIONES_ANTES,ATENCIONES_DESPUES
 FROM ds.Log_AuditoriaSIS WHERE ID_ATENCION=@Id ORDER BY ID_LOG DESC;
 ROLLBACK TRANSACTION PUNTO_PRUEBA;
 SELECT N'DESPUES DE SAVEPOINT' AS Momento,ID_ATENCION,ATENCIONES
 FROM dbo.ATENCIONES_SIS_OFICIAL WHERE ID_ATENCION=@Id;
 ROLLBACK TRANSACTION;
END TRY
BEGIN CATCH
 IF @@TRANCOUNT>0 ROLLBACK TRANSACTION;
 THROW;
END CATCH;
IF (SELECT ATENCIONES FROM dbo.ATENCIONES_SIS_OFICIAL WHERE ID_ATENCION=@Id)<>@ValorOriginal
 THROW 54011,N'La prueba ACID no restauro el valor original.',1;
PRINT N'Prueba ACID completada: datos originales preservados.';
GO
