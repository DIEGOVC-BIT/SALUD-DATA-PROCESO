USE MINSA;
GO
IF NOT EXISTS(SELECT 1 FROM sys.indexes WHERE object_id=OBJECT_ID(N'ref.IPRESS_MINSA') AND name=N'IX_IPRESS_Departamento_Provincia')
 CREATE NONCLUSTERED INDEX IX_IPRESS_Departamento_Provincia
 ON ref.IPRESS_MINSA(DEPARTAMENTO,PROVINCIA)
 INCLUDE(CODIGO_UNICO,NOMBRE_ESTABLECIMIENTO,CATEGORIA,DISTRITO);
GO
SET STATISTICS IO ON;
SET STATISTICS TIME ON;
SELECT CODIGO_UNICO,NOMBRE_ESTABLECIMIENTO,CATEGORIA,DISTRITO
FROM ref.IPRESS_MINSA
WHERE DEPARTAMENTO=N'LA LIBERTAD' AND PROVINCIA=N'PATAZ'
OPTION(RECOMPILE);
SET STATISTICS TIME OFF;
SET STATISTICS IO OFF;
GO
