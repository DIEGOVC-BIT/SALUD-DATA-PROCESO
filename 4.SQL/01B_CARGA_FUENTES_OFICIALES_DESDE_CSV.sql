/* 8. Trigger de integridad: impide valores fuera de regla y registra la
      validacion satisfactoria en la misma bitacora. Si falla, SQL Server revierte
      toda la transaccion (incluida la fila de log); el CATCH del procedimiento
      registra el error despues del rollback. */
CREATE OR ALTER TRIGGER dbo.trg_SIS_Oficial_Integridad
ON dbo.ATENCIONES_SIS_OFICIAL
AFTER INSERT, UPDATE
AS
BEGIN
 SET NOCOUNT ON;
 IF EXISTS(
  SELECT 1 FROM inserted
  WHERE ANO NOT BETWEEN 2000 AND 2100
     OR MES NOT BETWEEN 1 AND 12
     OR ATENCIONES < 0
     OR NULLIF(LTRIM(RTRIM(REGION)),N'') IS NULL
     OR NULLIF(LTRIM(RTRIM(PROVINCIA)),N'') IS NULL
     OR NULLIF(LTRIM(RTRIM(COD_IPRESS)),N'') IS NULL
     OR NULLIF(LTRIM(RTRIM(IPRESS)),N'') IS NULL
     OR NULLIF(LTRIM(RTRIM(DESC_SERVICIO)),N'') IS NULL
 )
  THROW 53110, 'Integridad SIS: año, mes, atenciones o campos obligatorios no cumplen las reglas.', 1;

 INSERT ds.Log_AuditoriaSIS(USUARIO,ACCION,ID_ATENCION,CLAVE_NEGOCIO,ATENCIONES_DESPUES,DETALLE)
 SELECT ORIGINAL_LOGIN(),N'VALIDACION_OK',ID_ATENCION,CLAVE_NEGOCIO,ATENCIONES,
        N'Trigger de integridad: registro validado correctamente'
 FROM inserted;
END;
GO

/* 9. SP #1: valida staging, registra filas rechazadas y crea ID de ejecucion.
      Incluye TRY/CATCH, transaccion y SAVE TRANSACTION (savepoint). */
CREATE OR ALTER PROCEDURE ds.sp_ValidarStagingSIS
 @IdEjecucion BIGINT OUTPUT
AS
BEGIN
 SET NOCOUNT ON;
 SET XACT_ABORT OFF;
 DECLARE @SavepointCreado BIT=0, @Error NVARCHAR(4000),
         @FilasOrigen BIGINT=0, @FilasRechazadas BIGINT=0, @FilasValidas BIGINT=0;
 SET @IdEjecucion=NULL;
 BEGIN TRY
  BEGIN TRANSACTION;
  INSERT ds.Log_EjecucionOficial(PROCESO,ESTADO,DETALLE)
  VALUES(N'sp_ValidarStagingSIS',N'EN_PROCESO',N'Inicio de validacion del staging SIS');
  SET @IdEjecucion=SCOPE_IDENTITY();
  SAVE TRANSACTION SP_VALIDAR_SIS;
  SET @SavepointCreado=1;

  SELECT @FilasOrigen=COUNT_BIG(*) FROM ds.vw_SIS_Staging_Normalizado;

  INSERT ds.SIS_RECHAZOS(ID_EJECUCION,CLAVE_FILA,MOTIVO,VALORES_FILA)
  SELECT @IdEjecucion,V.CLAVE_FILA,
   NULLIF(CONCAT(
    CASE WHEN V.ANO_N IS NULL OR V.ANO_N NOT BETWEEN 2000 AND 2100 THEN N'ANO_INVALIDO; ' ELSE N'' END,
    CASE WHEN V.MES_N IS NULL OR V.MES_N NOT BETWEEN 1 AND 12 THEN N'MES_INVALIDO; ' ELSE N'' END,
    CASE WHEN V.ATENCIONES_N IS NULL THEN N'ATENCIONES_NO_NUMERICAS_O_NULAS; '
         WHEN V.ATENCIONES_N<0 THEN N'ATENCIONES_NEGATIVAS; ' ELSE N'' END,
    CASE WHEN V.REGION_N IS NULL THEN N'REGION_VACIA; ' ELSE N'' END,
    CASE WHEN V.PROVINCIA_N IS NULL THEN N'PROVINCIA_VACIA; ' ELSE N'' END,
    CASE WHEN V.DISTRITO_N IS NULL THEN N'DISTRITO_VACIO; ' ELSE N'' END,
    CASE WHEN V.COD_IPRESS_N IS NULL THEN N'COD_IPRESS_VACIO; ' ELSE N'' END,
    CASE WHEN V.IPRESS_N IS NULL THEN N'IPRESS_VACIA; ' ELSE N'' END,
    CASE WHEN V.DESC_SERVICIO_N IS NULL THEN N'SERVICIO_VACIO; ' ELSE N'' END,
    CASE WHEN V.SEXO_N IS NULL THEN N'SEXO_VACIO; ' ELSE N'' END,
    CASE WHEN V.GRUPO_EDAD_N IS NULL THEN N'GRUPO_EDAD_VACIO; ' ELSE N'' END,
    CASE WHEN V.NRO_REPETICION>1 THEN N'DUPLICADO_EXACTO_EN_STAGING; ' ELSE N'' END),N''),
   (SELECT V.ANO_N AS ANO,V.MES_N AS MES,V.REGION_N AS REGION,V.PROVINCIA_N AS PROVINCIA,
    V.UBIGEO_DISTRITO_N AS UBIGEO_DISTRITO,V.DISTRITO_N AS DISTRITO,
    V.COD_UNIDAD_EJECUTORA_N AS COD_UNIDAD_EJECUTORA,V.DESC_UNIDAD_EJECUTORA_N AS DESC_UNIDAD_EJECUTORA,
    V.COD_IPRESS_N AS COD_IPRESS,V.IPRESS_N AS IPRESS,V.NIVEL_EESS_N AS NIVEL_EESS,
    V.PLAN_DE_SEGURO_N AS PLAN_DE_SEGURO,V.COD_SERVICIO_N AS COD_SERVICIO,
    V.DESC_SERVICIO_N AS DESC_SERVICIO,V.SEXO_N AS SEXO,V.GRUPO_EDAD_N AS GRUPO_EDAD,
    V.ATENCIONES_N AS ATENCIONES FOR JSON PATH, WITHOUT_ARRAY_WRAPPER)
  FROM ds.vw_SIS_Staging_Normalizado AS V
  WHERE V.ANO_N IS NULL OR V.ANO_N NOT BETWEEN 2000 AND 2100
     OR V.MES_N IS NULL OR V.MES_N NOT BETWEEN 1 AND 12
     OR V.ATENCIONES_N IS NULL OR V.ATENCIONES_N<0
     OR V.REGION_N IS NULL OR V.PROVINCIA_N IS NULL OR V.DISTRITO_N IS NULL
     OR V.COD_IPRESS_N IS NULL OR V.IPRESS_N IS NULL OR V.DESC_SERVICIO_N IS NULL
     OR V.SEXO_N IS NULL OR V.GRUPO_EDAD_N IS NULL
     OR V.NRO_REPETICION>1;

  SELECT @FilasRechazadas=COUNT_BIG(*) FROM ds.SIS_RECHAZOS WHERE ID_EJECUCION=@IdEjecucion;
  SET @FilasValidas=@FilasOrigen-@FilasRechazadas;
  UPDATE ds.Log_EjecucionOficial
   SET FECHA_FIN=SYSDATETIME(),ESTADO=CASE WHEN @FilasRechazadas=0 THEN N'VALIDADO' ELSE N'VALIDADO_CON_RECHAZOS' END,
       FILAS_ORIGEN=@FilasOrigen,FILAS_VALIDAS=@FilasValidas,FILAS_RECHAZADAS=@FilasRechazadas,
       DETALLE=N'Validacion finalizada. Revisar ds.SIS_RECHAZOS si existen filas observadas.'
   WHERE ID_EJECUCION=@IdEjecucion;
  COMMIT TRANSACTION;

  SELECT @IdEjecucion AS ID_EJECUCION,@FilasOrigen AS FILAS_ORIGEN,
         @FilasValidas AS FILAS_VALIDAS,@FilasRechazadas AS FILAS_RECHAZADAS;
 END TRY
 BEGIN CATCH
  SET @Error=ERROR_MESSAGE();
  IF XACT_STATE()=1 AND @SavepointCreado=1
  BEGIN
   ROLLBACK TRANSACTION SP_VALIDAR_SIS;
   UPDATE ds.Log_EjecucionOficial SET FECHA_FIN=SYSDATETIME(),ESTADO=N'ERROR',DETALLE=@Error
    WHERE ID_EJECUCION=@IdEjecucion;
   COMMIT TRANSACTION;
  END
  ELSE
  BEGIN
   IF XACT_STATE()<>0 ROLLBACK TRANSACTION;
   INSERT ds.Log_EjecucionOficial(PROCESO,FECHA_FIN,ESTADO,DETALLE)
    VALUES(N'sp_ValidarStagingSIS',SYSDATETIME(),N'ERROR',@Error);
  END;
  THROW;
 END CATCH
END;
GO

/* 10. SP #2: carga unicamente filas validadas; es idempotente por CLAVE_NEGOCIO.
       TRY/CATCH + BEGIN/COMMIT/ROLLBACK + SAVE TRANSACTION. */
CREATE OR ALTER PROCEDURE ds.sp_CargarAtencionesSISOficial
 @IdEjecucion BIGINT
AS
BEGIN
 SET NOCOUNT ON;
 SET XACT_ABORT OFF;
 DECLARE @SavepointCreado BIT=0,@Error NVARCHAR(4000),@FilasInsertadas BIGINT=0;
 BEGIN TRY
  IF NOT EXISTS(SELECT 1 FROM ds.Log_EjecucionOficial
                WHERE ID_EJECUCION=@IdEjecucion AND ESTADO IN(N'VALIDADO',N'VALIDADO_CON_RECHAZOS'))
   THROW 53120, 'El ID de ejecucion no existe o no tiene validacion terminada.', 1;

  BEGIN TRANSACTION;
  UPDATE ds.Log_EjecucionOficial SET ESTADO=N'CARGANDO',DETALLE=N'Iniciando insercion de filas SIS validadas'
   WHERE ID_EJECUCION=@IdEjecucion;
  SAVE TRANSACTION SP_CARGAR_SIS;
  SET @SavepointCreado=1;

  INSERT dbo.ATENCIONES_SIS_OFICIAL(
   ANO,MES,REGION,PROVINCIA,UBIGEO_DISTRITO,DISTRITO,COD_UNIDAD_EJECUTORA,DESC_UNIDAD_EJECUTORA,
   COD_IPRESS,IPRESS,NIVEL_EESS,PLAN_DE_SEGURO,COD_SERVICIO,DESC_SERVICIO,SEXO,GRUPO_EDAD,ATENCIONES,CLAVE_NEGOCIO)
  SELECT V.ANO_N,V.MES_N,V.REGION_N,V.PROVINCIA_N,V.UBIGEO_DISTRITO_N,V.DISTRITO_N,
   V.COD_UNIDAD_EJECUTORA_N,V.DESC_UNIDAD_EJECUTORA_N,V.COD_IPRESS_N,V.IPRESS_N,V.NIVEL_EESS_N,
   V.PLAN_DE_SEGURO_N,V.COD_SERVICIO_N,V.DESC_SERVICIO_N,V.SEXO_N,V.GRUPO_EDAD_N,V.ATENCIONES_N,V.CLAVE_FILA
  FROM ds.vw_SIS_Staging_Normalizado AS V
  WHERE V.ANO_N BETWEEN 2000 AND 2100 AND V.MES_N BETWEEN 1 AND 12
    AND V.ATENCIONES_N>=0 AND V.REGION_N IS NOT NULL AND V.PROVINCIA_N IS NOT NULL
    AND V.DISTRITO_N IS NOT NULL AND V.COD_IPRESS_N IS NOT NULL AND V.IPRESS_N IS NOT NULL
    AND V.DESC_SERVICIO_N IS NOT NULL AND V.SEXO_N IS NOT NULL AND V.GRUPO_EDAD_N IS NOT NULL
    AND V.NRO_REPETICION=1
    AND NOT EXISTS(SELECT 1 FROM dbo.ATENCIONES_SIS_OFICIAL T WITH(UPDLOCK,HOLDLOCK)
                   WHERE T.CLAVE_NEGOCIO=V.CLAVE_FILA);
  SET @FilasInsertadas=@@ROWCOUNT;

  UPDATE ds.Log_EjecucionOficial SET FECHA_FIN=SYSDATETIME(),ESTADO=N'CARGADO',
   FILAS_INSERTADAS=@FilasInsertadas,
   DETALLE=CONCAT(N'Carga idempotente finalizada. Filas nuevas: ',@FilasInsertadas,
                  N'. Si se repite el proceso, no duplica claves de negocio.')
  WHERE ID_EJECUCION=@IdEjecucion;
  COMMIT TRANSACTION;
  SELECT @IdEjecucion AS ID_EJECUCION,@FilasInsertadas AS FILAS_INSERTADAS;
 END TRY
 BEGIN CATCH
  SET @Error=ERROR_MESSAGE();
  IF XACT_STATE()=1 AND @SavepointCreado=1
  BEGIN
   ROLLBACK TRANSACTION SP_CARGAR_SIS;
   UPDATE ds.Log_EjecucionOficial SET FECHA_FIN=SYSDATETIME(),ESTADO=N'ERROR',DETALLE=@Error
    WHERE ID_EJECUCION=@IdEjecucion;
   COMMIT TRANSACTION;
  END
  ELSE
  BEGIN
   IF XACT_STATE()<>0 ROLLBACK TRANSACTION;
   UPDATE ds.Log_EjecucionOficial SET FECHA_FIN=SYSDATETIME(),ESTADO=N'ERROR',DETALLE=@Error
    WHERE ID_EJECUCION=@IdEjecucion;
  END;
  THROW;
 END CATCH
END;
GO

/* 11. SP #3: actualiza/inserta el catalogo IPRESS (upsert sin MERGE), con
       TRY/CATCH y savepoint. Los codigos se conservan como texto. */
CREATE OR ALTER PROCEDURE ds.sp_ActualizarCatalogoIPRESS
AS
BEGIN
 SET NOCOUNT ON;
 SET XACT_ABORT OFF;
 DECLARE @Id BIGINT=NULL,@SavepointCreado BIT=0,@Error NVARCHAR(4000),
         @Origen BIGINT=0,@Insertadas BIGINT=0,@Actualizadas BIGINT=0;
 BEGIN TRY
  BEGIN TRANSACTION;
  INSERT ds.Log_EjecucionOficial(PROCESO,ESTADO,DETALLE)
   VALUES(N'sp_ActualizarCatalogoIPRESS',N'EN_PROCESO',N'Actualizacion del catalogo de establecimientos');
  SET @Id=SCOPE_IDENTITY();
  SAVE TRANSACTION SP_UPSERT_IPRESS;
  SET @SavepointCreado=1;
  SELECT @Origen=COUNT_BIG(*) FROM stg.MINSA_IPRESS_RAW;

  ;WITH S AS(
   SELECT *,ROW_NUMBER() OVER(PARTITION BY LTRIM(RTRIM(CODIGO_UNICO)) ORDER BY (SELECT NULL)) AS RN
   FROM stg.MINSA_IPRESS_RAW
   WHERE NULLIF(LTRIM(RTRIM(CODIGO_UNICO)),N'') IS NOT NULL
     AND NULLIF(LTRIM(RTRIM(NOMBRE_ESTABLECIMIENTO)),N'') IS NOT NULL
  )
  UPDATE D SET
   D.INSTITUCION=S.INSTITUCION,D.NOMBRE_ESTABLECIMIENTO=S.NOMBRE_ESTABLECIMIENTO,
   D.CLASIFICACION=S.CLASIFICACION,D.TIPO=S.TIPO,D.DEPARTAMENTO=S.DEPARTAMENTO,
   D.PROVINCIA=S.PROVINCIA,D.DISTRITO=S.DISTRITO,D.UBIGEO=S.UBIGEO,D.DIRECCION=S.DIRECCION,
   D.CODIGO_DISA=S.CODIGO_DISA,D.CODIGO_RED=S.CODIGO_RED,D.CODIGO_MICRORRED=S.CODIGO_MICRORRED,
   D.DISA=S.DISA,D.RED=S.RED,D.MICRORRED=S.MICRORRED,D.CODIGO_UE=S.CODIGO_UE,
   D.UNIDAD_EJECUTORA=S.UNIDAD_EJECUTORA,D.CATEGORIA=S.CATEGORIA,D.TELEFONO=S.TELEFONO,
   D.TIPO_DOC_CATEGORIZACION=S.TIPO_DOC_CATEGORIZACION,D.NRO_DOC_CATEGORIZACION=S.NRO_DOC_CATEGORIZACION,
   D.HORARIO=S.HORARIO,D.INICIO_ACTIVIDAD=S.INICIO_ACTIVIDAD,D.DIRECTOR_RESPONSABLE=S.DIRECTOR_RESPONSABLE,
   D.ESTADO=S.ESTADO,D.SITUACION=S.SITUACION,D.CONDICION=S.CONDICION,D.INSPECCION=S.INSPECCION,
   D.NORTE=S.NORTE,D.ESTE=S.ESTE,D.COTA=S.COTA,D.CAMAS=S.CAMAS,D.FECHA_CARGA=SYSDATETIME()
  FROM ref.IPRESS_MINSA D JOIN S ON D.CODIGO_UNICO=LTRIM(RTRIM(S.CODIGO_UNICO)) AND S.RN=1;
  SET @Actualizadas=@@ROWCOUNT;

  ;WITH S AS(
   SELECT *,ROW_NUMBER() OVER(PARTITION BY LTRIM(RTRIM(CODIGO_UNICO)) ORDER BY (SELECT NULL)) AS RN
   FROM stg.MINSA_IPRESS_RAW
   WHERE NULLIF(LTRIM(RTRIM(CODIGO_UNICO)),N'') IS NOT NULL
     AND NULLIF(LTRIM(RTRIM(NOMBRE_ESTABLECIMIENTO)),N'') IS NOT NULL
  )
  INSERT ref.IPRESS_MINSA(
   INSTITUCION,CODIGO_UNICO,NOMBRE_ESTABLECIMIENTO,CLASIFICACION,TIPO,DEPARTAMENTO,PROVINCIA,DISTRITO,
   UBIGEO,DIRECCION,CODIGO_DISA,CODIGO_RED,CODIGO_MICRORRED,DISA,RED,MICRORRED,CODIGO_UE,UNIDAD_EJECUTORA,
   CATEGORIA,TELEFONO,TIPO_DOC_CATEGORIZACION,NRO_DOC_CATEGORIZACION,HORARIO,INICIO_ACTIVIDAD,
   DIRECTOR_RESPONSABLE,ESTADO,SITUACION,CONDICION,INSPECCION,NORTE,ESTE,COTA,CAMAS)
  SELECT S.INSTITUCION,LTRIM(RTRIM(S.CODIGO_UNICO)),S.NOMBRE_ESTABLECIMIENTO,S.CLASIFICACION,S.TIPO,
   S.DEPARTAMENTO,S.PROVINCIA,S.DISTRITO,S.UBIGEO,S.DIRECCION,S.CODIGO_DISA,S.CODIGO_RED,
   S.CODIGO_MICRORRED,S.DISA,S.RED,S.MICRORRED,S.CODIGO_UE,S.UNIDAD_EJECUTORA,S.CATEGORIA,
   S.TELEFONO,S.TIPO_DOC_CATEGORIZACION,S.NRO_DOC_CATEGORIZACION,S.HORARIO,S.INICIO_ACTIVIDAD,
   S.DIRECTOR_RESPONSABLE,S.ESTADO,S.SITUACION,S.CONDICION,S.INSPECCION,S.NORTE,S.ESTE,S.COTA,S.CAMAS
  FROM S WHERE S.RN=1 AND NOT EXISTS(
   SELECT 1 FROM ref.IPRESS_MINSA D WITH(UPDLOCK,HOLDLOCK)
   WHERE D.CODIGO_UNICO=LTRIM(RTRIM(S.CODIGO_UNICO)));
  SET @Insertadas=@@ROWCOUNT;

  UPDATE ds.Log_EjecucionOficial SET FECHA_FIN=SYSDATETIME(),ESTADO=N'CARGADO',
   FILAS_ORIGEN=@Origen,FILAS_INSERTADAS=@Insertadas,FILAS_ACTUALIZADAS=@Actualizadas,
   DETALLE=N'Catalogo IPRESS actualizado por codigo unico; no se eliminan filas existentes.'
  WHERE ID_EJECUCION=@Id;
  COMMIT TRANSACTION;
  SELECT @Id AS ID_EJECUCION,@Origen AS FILAS_ORIGEN,@Insertadas AS FILAS_INSERTADAS,@Actualizadas AS FILAS_ACTUALIZADAS;
 END TRY
 BEGIN CATCH
  SET @Error=ERROR_MESSAGE();
  IF XACT_STATE()=1 AND @SavepointCreado=1
  BEGIN
   ROLLBACK TRANSACTION SP_UPSERT_IPRESS;
   UPDATE ds.Log_EjecucionOficial SET FECHA_FIN=SYSDATETIME(),ESTADO=N'ERROR',DETALLE=@Error WHERE ID_EJECUCION=@Id;
   COMMIT TRANSACTION;
  END
  ELSE
  BEGIN
   IF XACT_STATE()<>0 ROLLBACK TRANSACTION;
   INSERT ds.Log_EjecucionOficial(PROCESO,FECHA_FIN,ESTADO,DETALLE)
    VALUES(N'sp_ActualizarCatalogoIPRESS',SYSDATETIME(),N'ERROR',@Error);
  END;
  THROW;
 END CATCH
END;
GO

