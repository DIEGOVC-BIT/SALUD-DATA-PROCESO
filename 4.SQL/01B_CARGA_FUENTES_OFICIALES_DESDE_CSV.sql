/* 5. Vista de normalizacion. La huella identifica la combinacion de dimensiones
      y permite evitar duplicados en una recarga. */
CREATE OR ALTER VIEW ds.vw_SIS_Staging_Normalizado
AS
WITH N AS(
 SELECT
  TRY_CONVERT(SMALLINT,NULLIF(LTRIM(RTRIM(ANO)),N'')) AS ANO_N,
  TRY_CONVERT(TINYINT,NULLIF(LTRIM(RTRIM(MES)),N'')) AS MES_N,
  NULLIF(LTRIM(RTRIM(REGION)),N'') AS REGION_N,
  NULLIF(LTRIM(RTRIM(PROVINCIA)),N'') AS PROVINCIA_N,
  NULLIF(LTRIM(RTRIM(UBIGEO_DISTRITO)),N'') AS UBIGEO_DISTRITO_N,
  NULLIF(LTRIM(RTRIM(DISTRITO)),N'') AS DISTRITO_N,
  NULLIF(LTRIM(RTRIM(COD_UNIDAD_EJECUTORA)),N'') AS COD_UNIDAD_EJECUTORA_N,
  NULLIF(LTRIM(RTRIM(DESC_UNIDAD_EJECUTORA)),N'') AS DESC_UNIDAD_EJECUTORA_N,
  NULLIF(LTRIM(RTRIM(COD_IPRESS)),N'') AS COD_IPRESS_N,
  NULLIF(LTRIM(RTRIM(IPRESS)),N'') AS IPRESS_N,
  NULLIF(LTRIM(RTRIM(NIVEL_EESS)),N'') AS NIVEL_EESS_N,
  NULLIF(LTRIM(RTRIM(PLAN_DE_SEGURO)),N'') AS PLAN_DE_SEGURO_N,
  NULLIF(LTRIM(RTRIM(COD_SERVICIO)),N'') AS COD_SERVICIO_N,
  NULLIF(LTRIM(RTRIM(DESC_SERVICIO)),N'') AS DESC_SERVICIO_N,
  NULLIF(LTRIM(RTRIM(SEXO)),N'') AS SEXO_N,
  NULLIF(LTRIM(RTRIM(GRUPO_EDAD)),N'') AS GRUPO_EDAD_N,
  TRY_CONVERT(BIGINT,NULLIF(LTRIM(RTRIM(ATENCIONES)),N'')) AS ATENCIONES_N
 FROM stg.SIS_ATENCIONES_RAW
), H AS(
 SELECT N.*,
  CONVERT(BINARY(32),HASHBYTES('SHA2_256',CONCAT(
   COALESCE(CONVERT(NVARCHAR(10),ANO_N),N'!'),N'|',COALESCE(CONVERT(NVARCHAR(3),MES_N),N'!'),N'|',
   COALESCE(UPPER(UBIGEO_DISTRITO_N),N''),N'|',COALESCE(UPPER(COD_IPRESS_N),N''),N'|',
   COALESCE(UPPER(COD_SERVICIO_N),N''),N'|',COALESCE(UPPER(PLAN_DE_SEGURO_N),N''),N'|',
   COALESCE(UPPER(REGION_N),N''),N'|',COALESCE(UPPER(PROVINCIA_N),N''),N'|',
   COALESCE(UPPER(DISTRITO_N),N''),N'|',COALESCE(UPPER(IPRESS_N),N''),N'|',
   COALESCE(UPPER(DESC_SERVICIO_N),N''),N'|',COALESCE(UPPER(SEXO_N),N''),N'|',
   COALESCE(UPPER(GRUPO_EDAD_N),N''),N'|',COALESCE(COD_UNIDAD_EJECUTORA_N,N''),N'|',
   COALESCE(DESC_UNIDAD_EJECUTORA_N,N''),N'|',COALESCE(NIVEL_EESS_N,N''),N'|',
   COALESCE(CONVERT(NVARCHAR(30),ATENCIONES_N),N'!')))) AS CLAVE_FILA
 FROM N
)
SELECT H.*,
 ROW_NUMBER() OVER(PARTITION BY CLAVE_FILA ORDER BY (SELECT NULL)) AS NRO_REPETICION
FROM H;
GO

/* 6. Funcion reutilizable. Umbrales heredados del modelo inicial del proyecto:
      <10 baja, 10-49 media y >=50 alta. Se documentan como regla de negocio. */
CREATE OR ALTER FUNCTION ds.fn_ClasificarDemandaSIS(@Cantidad BIGINT)
RETURNS NVARCHAR(20)
AS
BEGIN
 RETURN CASE WHEN @Cantidad IS NULL THEN N'SIN DATO'
             WHEN @Cantidad < 10 THEN N'BAJA'
             WHEN @Cantidad < 50 THEN N'MEDIA'
             ELSE N'ALTA' END;
END;
GO

/* 7. Trigger DML de auditoria: INSERT, UPDATE y DELETE, incluso multirregistro. */
CREATE OR ALTER TRIGGER dbo.trg_SIS_Oficial_Auditoria
ON dbo.ATENCIONES_SIS_OFICIAL
AFTER INSERT, UPDATE, DELETE
AS
BEGIN
 SET NOCOUNT ON;
 INSERT ds.Log_AuditoriaSIS(USUARIO,ACCION,ID_ATENCION,CLAVE_NEGOCIO,ATENCIONES_ANTES,ATENCIONES_DESPUES,DETALLE)
 SELECT ORIGINAL_LOGIN(),
  CASE WHEN i.ID_ATENCION IS NOT NULL AND d.ID_ATENCION IS NOT NULL THEN N'UPDATE'
       WHEN i.ID_ATENCION IS NOT NULL THEN N'INSERT' ELSE N'DELETE' END,
  COALESCE(i.ID_ATENCION,d.ID_ATENCION),COALESCE(i.CLAVE_NEGOCIO,d.CLAVE_NEGOCIO),
  d.ATENCIONES,i.ATENCIONES,N'Operación DML sobre dbo.ATENCIONES_SIS_OFICIAL'
 FROM inserted AS i
 FULL OUTER JOIN deleted AS d ON i.ID_ATENCION=d.ID_ATENCION;
END;
GO

