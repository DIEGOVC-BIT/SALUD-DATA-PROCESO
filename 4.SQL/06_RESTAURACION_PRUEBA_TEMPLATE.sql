/* DATASALUD PERU - PLANTILLA DE RESTAURACION DE PRUEBA
   1) Primero ejecutar RESTORE FILELISTONLY y copiar los LogicalName exactos.
   2) Reemplazar <LOGICAL_DATA_NAME> y <LOGICAL_LOG_NAME>.
   3) Confirmar que C:\SQLData\ existe y que el servicio SQL Server puede escribir.
   4) Ejecutar primero FULL con NORECOVERY y luego DIFFERENTIAL con RECOVERY.
   Nunca restaurar encima de MINSA de trabajo; usar MINSA_PRUEBA.
*/
RESTORE FILELISTONLY FROM DISK=N'C:\BackUp_MINSA\MINSA_Full.bak';
GO

RESTORE DATABASE MINSA_PRUEBA
FROM DISK=N'C:\BackUp_MINSA\MINSA_Full.bak'
WITH MOVE N'<LOGICAL_DATA_NAME>' TO N'C:\SQLData\MINSA_PRUEBA.mdf',
     MOVE N'<LOGICAL_LOG_NAME>'  TO N'C:\SQLData\MINSA_PRUEBA_log.ldf',
     NORECOVERY,REPLACE,STATS=10;
GO

RESTORE DATABASE MINSA_PRUEBA
FROM DISK=N'C:\BackUp_MINSA\MINSA_Diff.bak'
WITH RECOVERY,STATS=10;
GO

USE MINSA_PRUEBA;
GO
