USE MINSA;
GO
SET NOCOUNT ON;

PRINT '1. CONTEO Y CONCILIACION DE FUENTES';
SELECT COUNT_BIG(*) AS REGISTROS_SIS,
       SUM(ATENCIONES) AS TOTAL_ATENCIONES,
       COUNT(DISTINCT COD_IPRESS) AS CODIGOS_IPRESS_DISTINTOS
FROM dbo.ATENCIONES_SIS_OFICIAL;
SELECT COUNT_BIG(*) AS REGISTROS_IPRESS FROM ref.IPRESS_MINSA;
SELECT COUNT_BIG(*) AS FILAS_STAGING_SIS FROM stg.SIS_ATENCIONES_RAW;
SELECT COUNT_BIG(*) AS FILAS_STAGING_IPRESS FROM stg.MINSA_IPRESS_RAW;
GO

PRINT '2. COBERTURA DE CRUCE SIS - CATALOGO IPRESS';
;WITH CODIGOS AS(
 SELECT DISTINCT LTRIM(RTRIM(COD_IPRESS)) AS COD_IPRESS
 FROM dbo.ATENCIONES_SIS_OFICIAL
 WHERE NULLIF(LTRIM(RTRIM(COD_IPRESS)),N'') IS NOT NULL
)
SELECT COUNT_BIG(*) AS CODIGOS_SIS,
       SUM(CASE WHEN I.CODIGO_UNICO IS NOT NULL THEN 1 ELSE 0 END) AS CODIGOS_ENCONTRADOS,
       SUM(CASE WHEN I.CODIGO_UNICO IS NULL THEN 1 ELSE 0 END) AS CODIGOS_SIN_COINCIDENCIA,
       CAST(100.0*SUM(CASE WHEN I.CODIGO_UNICO IS NOT NULL THEN 1 ELSE 0 END)/NULLIF(COUNT_BIG(*),0) AS DECIMAL(6,2)) AS PORCENTAJE_COINCIDENCIA
FROM CODIGOS C
LEFT JOIN ref.IPRESS_MINSA I ON I.CODIGO_UNICO=C.COD_IPRESS;
GO

PRINT '3. RECHAZOS Y EJECUCIONES';
SELECT TOP(20) * FROM ds.Log_EjecucionOficial ORDER BY ID_EJECUCION DESC;
SELECT TOP(30) * FROM ds.SIS_RECHAZOS ORDER BY ID_RECHAZO DESC;
GO

PRINT '4. EVIDENCIA DE TRIGGERS Y AUDITORIA';
SELECT ACCION,COUNT_BIG(*) AS CANTIDAD
FROM ds.Log_AuditoriaSIS
GROUP BY ACCION ORDER BY ACCION;
SELECT TOP(30) * FROM ds.Log_AuditoriaSIS ORDER BY ID_LOG DESC;
GO

PRINT '5. COMPROBACION DE OBJETOS EXIGIDOS';
SELECT O.type_desc,O.name
FROM sys.objects O
WHERE O.name IN(
 N'sp_ValidarStagingSIS',N'sp_CargarAtencionesSISOficial',N'sp_ActualizarCatalogoIPRESS',
 N'trg_SIS_Oficial_Auditoria',N'trg_SIS_Oficial_Integridad',N'fn_ClasificarDemandaSIS'
)
ORDER BY O.type_desc,O.name;
GO

PRINT '6. FUNCION REUTILIZABLE Y RESUMEN ANALITICO';
SELECT ANO,PROVINCIA,DESC_SERVICIO,SUM(ATENCIONES) AS TOTAL_ATENCIONES,
       ds.fn_ClasificarDemandaSIS(SUM(ATENCIONES)) AS NIVEL_DEMANDA
FROM dbo.ATENCIONES_SIS_OFICIAL
GROUP BY ANO,PROVINCIA,DESC_SERVICIO
ORDER BY TOTAL_ATENCIONES DESC;
GO

PRINT '7. CONTROL DE DUPLICADOS';
SELECT COUNT_BIG(*) AS FILAS,
       COUNT_BIG(DISTINCT CLAVE_NEGOCIO) AS CLAVES_NEGOCIO_DISTINTAS,
       COUNT_BIG(*)-COUNT_BIG(DISTINCT CLAVE_NEGOCIO) AS DUPLICADOS
FROM dbo.ATENCIONES_SIS_OFICIAL;
GO
